  AND ControlId IN ('hCrearTurno', 'lblEspecialidad', 'lblBuscarNombre', 'lblMedico', 'lblDia', 'lblHora', 'spanAyudaFechas');

INSERT INTO dbo.ClaveTexto (Pagina, ControlId, TextoBase)
SELECT c.Pagina, c.ControlId, c.TextoBase
FROM #Catalogo c
WHERE NOT EXISTS (SELECT 1 FROM dbo.ClaveTexto k WHERE k.Pagina = c.Pagina AND k.ControlId = c.ControlId);

INSERT INTO dbo.Traduccion (IdIdioma, IdClave, Texto)
SELECT @IdEs, k.IdClave, k.TextoBase
FROM dbo.ClaveTexto k
JOIN #Catalogo c ON c.Pagina = k.Pagina AND c.ControlId = k.ControlId
WHERE NOT EXISTS (SELECT 1 FROM dbo.Traduccion t WHERE t.IdIdioma = @IdEs AND t.IdClave = k.IdClave);

UPDATE t SET Texto = c.TextoEn
FROM dbo.Traduccion t
JOIN dbo.ClaveTexto k ON k.IdClave = t.IdClave
JOIN #Catalogo c ON c.Pagina = k.Pagina AND c.ControlId = k.ControlId
WHERE t.IdIdioma = @IdEn AND LTRIM(RTRIM(t.Texto)) = '';

INSERT INTO dbo.Traduccion (IdIdioma, IdClave, Texto)
SELECT @IdEn, k.IdClave, c.TextoEn
FROM dbo.ClaveTexto k
JOIN #Catalogo c ON c.Pagina = k.Pagina AND c.ControlId = k.ControlId
WHERE NOT EXISTS (SELECT 1 FROM dbo.Traduccion t WHERE t.IdIdioma = @IdEn AND t.IdClave = k.IdClave);

COMMIT TRANSACTION;

